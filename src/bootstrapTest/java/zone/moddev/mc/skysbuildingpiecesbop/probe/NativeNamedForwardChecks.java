package zone.moddev.mc.skysbuildingpiecesbop.probe;

import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import java.io.File;
import java.io.FileInputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.LinkedHashSet;
import java.util.Set;
import java.util.UUID;
import net.minecraft.core.BlockPos;
import net.minecraft.nbt.CompoundTag;
import net.minecraft.nbt.NbtUtils;
import net.minecraft.nbt.Tag;
import net.minecraft.nbt.TagParser;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.world.entity.item.ItemEntity;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.level.ChunkPos;
import net.minecraft.world.level.block.entity.ChestBlockEntity;
import zone.moddev.mc.skysbuildingpieces.legacy.PiecesWorldState;

/** Check a world generated by the exact previous release, including asynchronous entity storage. */
final class NativeNamedForwardChecks {
    private static final Set<ChunkPos> CHUNKS = new LinkedHashSet<>();
    private static final Set<UUID> ENTITIES = new LinkedHashSet<>();
    private static JsonObject fixture;

    private NativeNamedForwardChecks() {
    }

    static boolean applies(File file) throws Exception {
        if (!file.isFile()) {
            return false;
        }
        try (InputStreamReader reader = new InputStreamReader(new FileInputStream(file), StandardCharsets.UTF_8)) {
            JsonObject saved = new JsonParser().parse(reader).getAsJsonObject();
            if (saved.has("kind") && saved.get("kind").getAsString().equals("named")) {
                fixture = saved;
                return true;
            }
            return false;
        }
    }

    static void prepare(ServerLevel world) throws Exception {
        CHUNKS.clear();
        ENTITIES.clear();
        NativeSavedBiomeChecks.prepare(world, CHUNKS);
        Set<ChunkPos> deferred = NativeSavedBiomeChecks.deferredChunks();
        for (String list : new String[] { "states", "containers", "entities" }) {
            for (JsonElement value : fixture.getAsJsonArray(list)) {
                JsonObject saved = value.getAsJsonObject();
                ChunkPos chunk = new ChunkPos(position(saved));
                if (deferred.contains(chunk)) {
                    require(list.equals("states"), "A deferred biome chunk contains a saved inventory or entity");
                    continue;
                }
                CHUNKS.add(chunk);
                if (list.equals("entities")) {
                    ENTITIES.add(UUID.fromString(saved.get("uuid").getAsString()));
                }
            }
        }
        for (ChunkPos chunk : CHUNKS) {
            world.setChunkForced(chunk.x, chunk.z, true);
            world.getChunk(chunk.x, chunk.z);
        }
    }

    static boolean ready(ServerLevel world) {
        for (ChunkPos chunk : CHUNKS) {
            if (!world.areEntitiesLoaded(chunk.toLong())
                    || !world.getChunkSource().isPositionTicking(chunk.toLong())) {
                return false;
            }
        }
        return ENTITIES.stream().allMatch(identity -> world.getEntity(identity) != null);
    }

    static void run(ServerLevel world) throws Exception {
        NativeSavedBiomeChecks.verify(world);
        int states = 0;
        int crystals = 0;
        Set<ChunkPos> deferred = NativeSavedBiomeChecks.deferredChunks();
        for (JsonElement value : fixture.getAsJsonArray("states")) {
            JsonObject saved = value.getAsJsonObject();
            if (deferred.contains(new ChunkPos(position(saved)))) {
                require(world.getChunkSource().getChunkNow(position(saved).getX() >> 4,
                        position(saved).getZ() >> 4) == null, "A deferred source chunk was loaded early");
                continue;
            }
            CompoundTag expected = TagParser.parseTag(saved.get("state").getAsString());
            String source = expected.getString("Name");
            if (source.equals("biomesoplenty:rose_quartz_cluster") || source.equals("biomesoplenty:rose_quartz_block")) {
                crystals++;
            } else if (source.equals("biomesoplenty:mangrove_root")) {
                expected.putString("Name", "minecraft:small_dripleaf");
                expected.getCompound("Properties").putString("facing", "north");
            } else if (source.equals("biomesoplenty:tree_roots")) {
                expected.putString("Name", "minecraft:weeping_vines");
            } else if (source.equals("biomesoplenty:tree_roots_stem")) {
                expected.putString("Name", "minecraft:weeping_vines_plant");
            } else if (source.equals("biomesoplenty:nether_crystal")) {
                CompoundTag properties = expected.getCompound("Properties");
                String face = properties.getString("face");
                String direction = face.equals("floor") ? "up"
                        : face.equals("ceiling") ? "down" : properties.getString("facing");
                CompoundTag replacement = new CompoundTag();
                replacement.putString("facing", direction);
                replacement.putString("waterlogged", "false");
                expected.putString("Name", "biomesoplenty:rose_quartz_cluster");
                expected.put("Properties", replacement);
                crystals++;
            } else if (source.equals("biomesoplenty:nether_crystal_block")) {
                expected.putString("Name", "biomesoplenty:rose_quartz_block");
                crystals++;
            } else if (source.equals("minecraft:grass_path")) {
                expected.putString("Name", "minecraft:dirt_path");
            } else if (source.equals("biomesoplenty:rooted_sand")) {
                expected.putString("Name", "minecraft:rooted_dirt");
            } else if (java.util.Set.of("biomesoplenty:mud", "biomesoplenty:mud_bricks",
                    "biomesoplenty:mud_brick_slab", "biomesoplenty:mud_brick_stairs",
                    "biomesoplenty:mud_brick_wall").contains(source)) {
                expected.putString("Name", source.replace("biomesoplenty:", "minecraft:"));
                if (source.equals("biomesoplenty:mud_brick_slab")
                        && expected.getCompound("Properties").getString("type").equals("double")) {
                    expected.putString("Name", "minecraft:mud_bricks");
                    expected.remove("Properties");
                }
            }
            net.minecraft.world.level.block.state.BlockState decoded = NbtUtils.readBlockState(net.minecraft.core.registries.BuiltInRegistries.BLOCK.asLookup(), expected);
            if (decoded.getBlock() instanceof zone.moddev.mc.skysbuildingpieces.content.PieceBlock) {
                // Old palette holders remain registered, but their native BOP
                // equivalents are the accepted stored form after loading.
                expected = NbtUtils.writeBlockState(
                        zone.moddev.mc.skysbuildingpieces.content.Pieces.canonicalState(decoded));
            }
            CompoundTag actual = NbtUtils.writeBlockState(world.getBlockState(position(saved)));
            require(expected.equals(actual), "Saved block changed at " + position(saved) + ": " + actual
                    + ", expected " + expected);
            states++;
        }
        require(crystals == 13, "Every native crystal attachment and full block must be exercised");

        int units = 0;
        int baskets = 0;
        for (JsonElement value : fixture.getAsJsonArray("containers")) {
            JsonObject saved = value.getAsJsonObject();
            require(world.getBlockEntity(position(saved)) instanceof ChestBlockEntity, "Saved chest is missing");
            ChestBlockEntity chest = (ChestBlockEntity) world.getBlockEntity(position(saved));
            for (JsonElement item : saved.getAsJsonArray("items")) {
                JsonObject entry = item.getAsJsonObject();
                ItemStack actual = chest.getItem(entry.get("slot").getAsInt());
                ItemStack expected = expectedItem(entry.get("stack").getAsString());
                require(ItemStack.matches(expected, actual), "Saved inventory data changed: " + entry + ", actual "
                        + actual.save(new CompoundTag()));
                units += actual.getCount();
                if (actual.getItem() == zone.moddev.mc.skysbuildingpiecesbop.basket.Baskets.ITEM) {
                    require(actual.getTag().getList("Items", 10).equals(expected.getTag().getList("Items", 10)), "Saved basket lost a slot");
                    baskets++;
                }
            }
        }
        require(baskets == (fixture.has("original_baskets") ? fixture.getAsJsonArray("original_baskets").size() + 1 : 1), "Every source basket must survive");
        for (JsonElement value : fixture.getAsJsonArray("entities")) {
            JsonObject saved = value.getAsJsonObject();
            net.minecraft.world.entity.Entity entity = world.getEntity(UUID.fromString(saved.get("uuid").getAsString()));
            ItemStack expected = expectedItem(saved.get("stack").getAsString());
            require(entity instanceof ItemEntity && ItemStack.matches(expected, ((ItemEntity) entity).getItem()),
                    "Saved dropped item changed or disappeared");
            units += expected.getCount();
        }
        UUID playerId = UUID.fromString(fixture.get("player").getAsString());
        net.minecraftforge.common.util.FakePlayer player = net.minecraftforge.common.util.FakePlayerFactory.get(world,
                new com.mojang.authlib.GameProfile(playerId, "PieceFixture"));
        require(world.getServer().getPlayerList().load(player) != null, "Saved player data is missing");
        require(ItemStack.matches(expectedItem(fixture.get("player_shovel").getAsString()), player.getInventory().getItem(0)),
                "Player tool lost damage, enchantments, name or custom data");
        ItemStack nested = expectedItem(fixture.get("player_nested").getAsString());
        require(ItemStack.matches(nested, player.getInventory().getItem(1)), "Nested player inventory changed");
        require(ItemStack.matches(nested, player.getEnderChestInventory().getItem(0)), "Ender inventory changed");
        java.lang.reflect.Method save = null;
        for (java.lang.reflect.Method method : net.minecraft.server.players.PlayerList.class.getDeclaredMethods()) {
            if (java.lang.reflect.Modifier.isProtected(method.getModifiers()) && method.getReturnType() == void.class
                    && java.util.Arrays.equals(method.getParameterTypes(),
                            new Class<?>[] { net.minecraft.server.level.ServerPlayer.class })) {
                require(save == null, "Ambiguous native player-save method");
                save = method;
            }
        }
        require(save != null, "Native player-save method is missing");
        save.setAccessible(true);
        save.invoke(world.getServer().getPlayerList(), player);
        require(PiecesWorldState.get(world).save(new CompoundTag()).equals(
                TagParser.parseTag(fixture.get("world_state").getAsString())), "Saved schema or migration counters changed");
        for (ChunkPos chunk : CHUNKS) {
            world.setChunkForced(chunk.x, chunk.z, false);
        }
        ForwardUpgradeChecks.checkSavedRecoveryData(world);
        if (!deferred.isEmpty()) {
            java.nio.file.Files.writeString(java.nio.file.Path.of("delayed-biomes-first-pass.txt"),
                    "deferred_chunks=" + deferred.size() + "\n", StandardCharsets.UTF_8);
        }
        org.apache.logging.log4j.LogManager.getLogger().info("BUILDING_PIECES_BOP_FORWARD_UPGRADE_PASS named_states="
                + states + " crystals=" + crystals + " item_units=" + units + " basket_slots=18 schema=1 counters=unchanged");
    }

    private static ItemStack expectedItem(String text) throws Exception {
        CompoundTag saved = TagParser.parseTag(text);
        rewriteExpectedItems(saved);
        return ItemStack.of(saved);
    }

    private static void rewriteExpectedItems(Tag value) {
        if (value instanceof CompoundTag) {
            CompoundTag saved = (CompoundTag) value;
            if (saved.contains("Count", 99)) {
                String id = saved.getString("id");
                if (id.equals("minecraft:grass_path")) {
                    saved.putString("id", "minecraft:dirt_path");
                } else if (id.equals("biomesoplenty:rooted_sand")) {
                    saved.putString("id", "minecraft:rooted_dirt");
                } else if (id.equals("biomesoplenty:mud_ball")) {
                    saved.putString("id", "minecraft:clay_ball");
                } else if (id.equals("biomesoplenty:mud_brick")) {
                    saved.putString("id", "minecraft:brick");
                } else if (java.util.Set.of("biomesoplenty:mud", "biomesoplenty:mud_bricks",
                        "biomesoplenty:mud_brick_slab", "biomesoplenty:mud_brick_stairs",
                        "biomesoplenty:mud_brick_wall").contains(id)) {
                    saved.putString("id", id.replace("biomesoplenty:", "minecraft:"));
                } else if (id.equals("biomesoplenty:mangrove_root")) {
                    saved.putString("id", "minecraft:small_dripleaf");
                } else if (id.equals("biomesoplenty:tree_roots") || id.equals("biomesoplenty:tree_roots_stem")) {
                    saved.putString("id", "minecraft:weeping_vines");
                } else if (id.equals("biomesoplenty:nether_crystal_block")) {
                    saved.putString("id", "biomesoplenty:rose_quartz_block");
                } else if (id.equals("biomesoplenty:nether_crystal")) {
                    saved.putString("id", "biomesoplenty:rose_quartz_cluster");
                    CompoundTag properties = saved.getCompound("tag").getCompound("BlockStateTag");
                    if (!properties.isEmpty()) {
                        String face = properties.getString("face");
                        String direction = face.equals("floor") ? "up"
                                : face.equals("ceiling") ? "down" : properties.getString("facing");
                        properties.remove("face");
                        properties.putString("facing", direction);
                        properties.putString("waterlogged", "false");
                    }
                }
            }
            for (String key : saved.getAllKeys()) {
                rewriteExpectedItems(saved.get(key));
            }
        } else if (value instanceof net.minecraft.nbt.ListTag) {
            for (Tag child : (net.minecraft.nbt.ListTag) value) {
                rewriteExpectedItems(child);
            }
        }
    }

    private static BlockPos position(JsonObject value) {
        return new BlockPos(value.get("x").getAsInt(), value.get("y").getAsInt(), value.get("z").getAsInt());
    }

    private static void require(boolean condition, String message) {
        if (!condition) {
            throw new AssertionError(message);
        }
    }
}
